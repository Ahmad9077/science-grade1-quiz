import fs from 'node:fs/promises'
import process from 'node:process'
import { AUDIENCES, QUESTIONS, type Audience } from '../src/data/catalog.ts'

const outputUrl = new URL('../integration/seed-science-grade1.sql', import.meta.url)
const PRODUCTION_URL = 'https://ahmad9077.github.io/science-grade1-quiz/'

// Both copies share the lessons and question keys; each is its own Hub quiz.
const COPIES: Record<Audience, { url: string; color: string; sortOrder: number }> = {
  girls: { url: PRODUCTION_URL, color: '#e3f6dc', sortOrder: 110 },
  boys: { url: `${PRODUCTION_URL}boys/`, color: '#dcecfb', sortOrder: 111 },
}
const audiences = Object.keys(COPIES) as Audience[]
const quizIds = audiences.map((audience) => AUDIENCES[audience].quizId)

function sqlText(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function sqlArray(values: string[]): string {
  return `array[${values.map(sqlText).join(', ')}]`
}

const quizRows = audiences.map((audience) => {
  const { quizId, title } = AUDIENCES[audience]
  const copy = COPIES[audience]
  return `  (${sqlText(quizId)}, ${sqlText(title)}, ${sqlText(copy.url)}, '🔬', ${sqlText(copy.color)}, ${copy.sortOrder})`
})

const rows = quizIds.flatMap((quizId) =>
  QUESTIONS.map((question) => {
    const topics = ['science_grade1', `topic_${question.topic}`, `kind_${question.kind}`]
    const skills = question.skills.map((skill) => skill.replaceAll('-', '_'))
    return `  (${sqlText(quizId)}, ${sqlText(question.key)}, ${question.difficulty}, ${sqlArray(topics)}, ${sqlArray(skills)})`
  }),
)

const sql = `-- Hub registration for «علوم - بنات» and «علوم - أولاد» (Grade 1 science practice).
-- Generated by scripts/generate-hub-seed.ts. Apply only after the production site is approved and live.
-- Registers both catalog rows and their adaptive question profiles. Intentionally creates no quiz_assignments.

begin;

insert into public.quizzes (id, title, url, icon, color, sort_order)
values
${quizRows.join(',\n')}
on conflict (id) do update set
  title = excluded.title,
  url = excluded.url,
  icon = excluded.icon,
  color = excluded.color,
  sort_order = excluded.sort_order;

insert into public.question_difficulty_profiles (
  quiz_id,
  question_key,
  difficulty,
  topic_tags,
  skill_tags
)
values
${rows.join(',\n')}
on conflict (quiz_id, question_key) do update set
  difficulty = excluded.difficulty,
  topic_tags = excluded.topic_tags,
  skill_tags = excluded.skill_tags,
  updated_at = now();

do $$
begin
${quizIds
  .map(
    (quizId) => `  if (select count(*) from public.question_difficulty_profiles where quiz_id = ${sqlText(quizId)}) <> ${QUESTIONS.length} then
    raise exception '${quizId} profile count must be exactly ${QUESTIONS.length}';
  end if;`,
  )
  .join('\n')}
end
$$;

commit;

select
  quiz_id,
  count(*) as seeded_questions,
  min(difficulty) as min_difficulty,
  max(difficulty) as max_difficulty
from public.question_difficulty_profiles
where quiz_id in (${quizIds.map(sqlText).join(', ')})
group by quiz_id
order by quiz_id;
`

if (process.argv.includes('--check')) {
  const existing = await fs.readFile(outputUrl, 'utf8').catch(() => '')
  if (existing !== sql) throw new Error('Hub seed is stale. Run npm run generate:hub-seed.')
  console.log(`Hub seed is current with ${QUESTIONS.length} adaptive profiles for each of ${quizIds.join(', ')}.`)
} else {
  await fs.mkdir(new URL('../integration/', import.meta.url), { recursive: true })
  await fs.writeFile(outputUrl, sql)
  console.log(`Generated ${QUESTIONS.length} adaptive profiles for each of ${quizIds.join(', ')} at ${outputUrl.pathname}`)
}
